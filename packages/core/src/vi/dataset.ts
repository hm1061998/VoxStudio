import path from 'node:path';
import type { ComponentCoverageDto, DatasetReportDto } from '@voxstudio/contracts';
import { parseSyllable, TONES } from './syllable';
import type { UnitDb } from './unitdb';

/**
 * Orthographic inventory of Vietnamese syllable components. A recorded-unit voice is complete only
 * when every required component occurs in its recordings. `optional` items occur only in loanwords
 * or place names; they are reported but do not make a dataset incomplete.
 */
export const COMPONENT_INVENTORY = {
  onsets: {
    required: [
      '',
      'b',
      'c',
      'ch',
      'd',
      'đ',
      'g',
      'gh',
      'gi',
      'h',
      'kh',
      'l',
      'm',
      'n',
      'ng',
      'ngh',
      'nh',
      'ph',
      'q',
      'r',
      's',
      't',
      'th',
      'tr',
      'v',
      'x',
    ],
    optional: ['k', 'p'],
  },
  nuclei: {
    required: [
      'a',
      'ă',
      'â',
      'e',
      'ê',
      'i',
      'y',
      'o',
      'ô',
      'ơ',
      'u',
      'ư',
      'iê',
      'yê',
      'ươ',
      'uô',
      'ia',
      'ưa',
      'ua',
    ],
    optional: ['ya'],
  },
  codas: {
    required: ['', 'c', 'ch', 'm', 'n', 'ng', 'nh', 'p', 't', 'i', 'y', 'o', 'u'],
    optional: [] as string[],
  },
  tones: { required: [...TONES] as string[], optional: [] as string[] },
} as const;

export interface BenchSyllableList {
  corpusVersion: string;
  syllables: string[];
}

/** Load config/vi-bench-syllables.json (generated by scripts/gen-bench-syllables.mjs); null when absent. */
export function loadBenchSyllables(repoRoot: string): BenchSyllableList | null {
  const file = path.join(repoRoot, 'config', 'vi-bench-syllables.json');
  if (!existsSync(file)) return null;
  const j = JSON.parse(readFileSync(file, 'utf8')) as BenchSyllableList;
  return Array.isArray(j.syllables) && typeof j.corpusVersion === 'string' ? j : null;
}

const pct = (sorted: number[], q: number): number =>
  sorted.length ? (sorted[Math.min(sorted.length - 1, Math.floor(q * (sorted.length - 1) + 0.5))] ?? 0) : 0;
const round = (n: number, d = 1): number => Math.round(n * 10 ** d) / 10 ** d;

function coverage(required: readonly string[], seen: Set<string>): ComponentCoverageDto {
  const missing = required.filter((r) => !seen.has(r));
  return { total: required.length, covered: required.length - missing.length, missing };
}

/**
 * Measure a unit database. Everything is computed from the stored unit metadata and manifest; nothing is
 * estimated or assumed. `bench` is optional: without it `corpus` is null (reported as "not checked").
 */
export function buildDatasetReport(
  db: UnitDb,
  bench: BenchSyllableList | null,
  region = db.manifest.dialect,
): DatasetReportDto {
  const m = db.manifest;
  const seen = {
    onsets: new Set<string>(),
    nuclei: new Set<string>(),
    codas: new Set<string>(),
    tones: new Set<string>(),
  };
  const perSyllable = new Map<string, number>();
  const unitsPerTone: Record<string, number> = Object.fromEntries(TONES.map((t) => [t, 0]));
  for (const u of db.units) {
    const p = parseSyllable(u.key);
    if (!p.ok) continue;
    const s = p.syllable;
    seen.onsets.add(s.onset);
    seen.nuclei.add(s.nucleus);
    seen.codas.add(s.coda);
    seen.tones.add(s.tone);
    unitsPerTone[s.tone] = (unitsPerTone[s.tone] ?? 0) + 1;
    const k = db.canonicalKey(u.key);
    perSyllable.set(k, (perSyllable.get(k) ?? 0) + 1);
  }
  const components = {
    onsets: coverage(COMPONENT_INVENTORY.onsets.required, seen.onsets),
    nuclei: coverage(COMPONENT_INVENTORY.nuclei.required, seen.nuclei),
    codas: coverage(COMPONENT_INVENTORY.codas.required, seen.codas),
    tones: coverage(COMPONENT_INVENTORY.tones.required, seen.tones),
  };
  let corpus: DatasetReportDto['corpus'] = null;
  if (bench) {
    const need = [...new Set(bench.syllables)];
    const missing = need.filter((s) => !db.has(s));
    corpus = {
      version: bench.corpusVersion,
      required: need.length,
      covered: need.length - missing.length,
      coveragePct: need.length ? round(((need.length - missing.length) / need.length) * 100) : 0,
      missing,
    };
  }
  const durations = db.units.map((u) => u.durationMs);
  const f0 = db.units
    .map((u) => u.f0Mean)
    .filter((x) => x > 0)
    .sort((a, b) => a - b);
  const rms = db.units
    .map((u) => u.rms)
    .filter((x) => x > 0)
    .map((x) => 20 * Math.log10(x))
    .sort((a, b) => a - b);
  const total = durations.reduce((a, b) => a + b, 0);
  const warnings: string[] = [];
  const shortUnits = durations.filter((d) => d < 60).length;
  const unvoiced = db.units.filter((u) => u.f0Mean === 0).length;
  const single = [...perSyllable.values()].filter((n) => n === 1).length;
  if (!m.datasetVersion)
    warnings.push('The dataset has no version label; set datasetVersion when building it.');
  if (!m.attribution && m.attribution !== '')
    warnings.push('No attribution record: confirm whether the license requires a credit line.');
  if (!m.speaker) warnings.push('No speaker record: gender is not stated and is not advertised.');
  if (!m.provenance)
    warnings.push('No provenance record: it is not stated whether the audio is human or AI-generated.');
  if (m.provenance?.kind === 'ai-generated')
    warnings.push(
      'The audio was generated with AI during development (' +
        (m.provenance.generator?.name ?? 'unknown generator') +
        '); this voice must not be presented as a human recording.',
    );
  if (m.license.id === 'test-fixture')
    warnings.push('Test fixture: derived from a formant synthesizer, not recorded speech.');
  if (shortUnits) warnings.push(`${shortUnits} unit(s) are shorter than 60 ms and may be mis-segmented.`);
  if (single)
    warnings.push(`${single} syllable(s) have a single recording, so unit selection has no choice.`);
  const missingParts = Object.entries(components)
    .filter(([, c]) => c.missing.length)
    .map(([k, c]) => `${k}: ${c.missing.join(' ')}`);
  if (missingParts.length) warnings.push(`Missing phonetic components — ${missingParts.join('; ')}.`);
  if (corpus?.missing.length)
    warnings.push(
      `${corpus.missing.length} benchmark syllable(s) have no unit; text using them fails with UNIT_MISSING.`,
    );
  if (!corpus) warnings.push('Benchmark coverage was not checked (no syllable list installed).');
  const complete =
    missingParts.length === 0 && !!corpus && corpus.missing.length === 0 && db.units.length > 0;
  return {
    schema: 'vn-dataset-report-1',
    datasetId: m.id,
    datasetVersion: m.datasetVersion ?? 'unversioned',
    builtBy: m.builtBy,
    unitsSha256: m.unitsSha256,
    manifestSha256: db.manifestSha256,
    units: db.units.length,
    distinctSyllables: perSyllable.size,
    singleInstanceSyllables: single,
    components,
    unitsPerTone,
    corpus,
    recording: {
      format: 'pcm_s16le',
      sampleRate: m.sampleRate,
      channels: 1,
      totalSeconds: round(total / 1000, 2),
      meanUnitMs: durations.length ? Math.round(total / durations.length) : 0,
      shortUnits,
      f0Hz: f0.length
        ? { p10: round(pct(f0, 0.1)), median: round(pct(f0, 0.5)), p90: round(pct(f0, 0.9)) }
        : null,
      rmsDbfs: rms.length
        ? { p10: round(pct(rms, 0.1)), median: round(pct(rms, 0.5)), p90: round(pct(rms, 0.9)) }
        : null,
      unvoicedUnits: unvoiced,
      notes: m.recordingNotes ?? '',
    },
    speaker: {
      gender: m.speaker?.genderVerified ? (m.speaker.gender ?? null) : null,
      genderVerified: !!m.speaker?.genderVerified,
      region,
    },
    license: { id: m.license.id, notes: m.license.notes, attribution: m.attribution ?? '' },
    provenance: {
      kind: m.provenance?.kind ?? 'unknown',
      generator: m.provenance?.generator ?? null,
      notes: m.provenance?.notes ?? '',
    },
    complete,
    warnings,
  };
}
